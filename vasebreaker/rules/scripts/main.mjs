  function fumeParticlePrefab(prefab, native) {
    const existing = fumePrefabs.get(prefab);
    if (existing) return existing;
    const db = prefab?.data?.getComponent?.(native.ArmatureDisplay);
    const source = db?.dragonAsset;
    if (!source || db.armatureName !== "AttackParticle") return prefab;
    let fixed = fumeAssets.get(source);
    if (!fixed) {
      const data = JSON.parse(source.dragonBonesJson);
      const arm = data.armature?.find(value => value.name === "AttackParticle");
      const play = arm?.animation?.find(value => value.name === "Play");
      if (!play || arm.animation.some(value => value.name === "Stop")) return prefab;
      let changed = false;
      for (const frame of play.frame ?? []) if (frame.action === "Stop" && frame.events?.some(event => event.name === "die")) {
        // The native end-frame event returns the smoke to its pool. The legacy
        // action wrongly requests a missing animation and must not replace it.
        delete frame.action;changed = true;
      }
      if (!changed) return prefab;
      fixed = new native.DragonBonesAsset();
      fixed._uuid = `${source._uuid || "fumeshroom"}-vase-chaos-smoke-${++fumeAssetSerial}`;
      fixed.dragonBonesJson = JSON.stringify(data);
      fumeAssets.set(source, fixed);
    }
    // Prepare a private, unparented template before native pool activation.
    // Replacing an already playing armature can leave queued old-frame events.
    const template = native.instantiate(prefab);
    template.name = `${prefab.name || template.name}-vase-chaos-smoke-${fumeAssetSerial}`;
    template.getComponent(native.ArmatureDisplay).dragonAsset = fixed;
    const copy = new native.Prefab();copy.name = template.name;copy.data = template;
    fumePrefabs.set(prefab, copy);
    return copy;
  }
  function restoreFumeParticles() {
    const pools = getNative().NodePools?.nodepools;
    for (const copy of fumePrefabs.values()) {
      if (pools?.[copy.name]) {pools[copy.name].clear();delete pools[copy.name];}
      copy.data?.destroy?.();copy.destroy?.();
    }
    fumePrefabs.clear();
    for (const node of fumeNodes) if (node.isValid !== false) node.destroy?.();
    fumeNodes.clear();
    for (const asset of fumeAssets.values()) asset.destroy?.();
    fumeAssets.clear();
  }
